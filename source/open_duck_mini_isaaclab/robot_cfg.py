#: 발바닥 접지면을 키운 변형 (2026-08-20). 운동학은 기존과 **완전 동일**하다
#: (14 축 부모·자식·축·rpy·xyz·한계 전부 일치, -0/0 표기 차이만 있음).
#: 질량 차이: 발 편측 69.5 -> 79.9 g, 그리고 몸통 1165.0 -> 1153.0 g
#: (릴레이를 실기에서 뺀 것이 반영됐다). 총 2743.0 -> 2751.8 g.
