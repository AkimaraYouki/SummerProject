# Leg joints (10): position-servo XM430, this exact set drives locomotion.
_LEG_JOINT_NAMES = [n for n in ACTUATOR_JOINT_NAMES if "hip" in n or "knee" in n or "ankle" in n]
# Head joints (4): same physical servo, but not part of the imitation reward
# and given a commanded (not learned) target — see reward docs.
_HEAD_JOINT_NAMES = [n for n in ACTUATOR_JOINT_NAMES if n not in _LEG_JOINT_NAMES]

assert set(_LEG_JOINT_NAMES) | set(_HEAD_JOINT_NAMES) == set(ACTUATOR_JOINT_NAMES)
assert len(_LEG_JOINT_NAMES) == 10 and len(_HEAD_JOINT_NAMES) == 4

