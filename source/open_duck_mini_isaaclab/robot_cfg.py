#:     기존      1907 mm^2   전후  99.3 mm   좌우 38.7 mm
#:     big_foot  2365 mm^2   전후 108.6 mm   좌우 42.9 mm
#: 즉 심의 좌우 지지는 +11 % 만 는다. STL 만 보고 적었던 "16.3 -> 40.0 mm,
