"""Isaac Lab ArticulationCfg for Open Duck Mini V2.

This robot's actual actuator is a Dynamixel XM430 (confirmed choice for the
rebuild — see docs/onshape_import.md), not the original project's STS3215.
Actuator gains below are sourced from the "m4"-model BAM characterization at
~/Desktop/robot make/bam_xm430_params/m4.json wherever BAM measures the
matching physical quantity directly:

  armature = 0.014317492733137276  (BAM "armature", direct)
  damping  = 0.8470782260272692    (BAM "friction_viscous" — closest concept
                                     to URDF/Isaac Lab's viscous joint damping;
                                     must stay in sync with
                                     scripts/convert_urdf.sh's --joint-damping)
  friction = 0.07610030458666567   (BAM "friction_base" — the Coulomb/base
                                     term only. BAM's m4 model is a full
                                     Stribeck friction curve — friction_base,
                                     friction_stribeck, load_friction_base,
                                     load_friction_stribeck, dtheta_stribeck,
                                     alpha — but ImplicitActuatorCfg.friction
                                     is a single scalar, so only the base term
                                     maps here. The velocity- and
                                     load-dependent terms have no home in this
                                     actuator model.)

Sourced from the ROBOTIS XM430-W350 datasheet instead of BAM (m4.json has no
torque/speed limit fields), at the confirmed operating voltage of 12.0V —
https://docs.robotis.com/docs/dxl/model_reference/x_series/xm_series/xm430-w350 :

  effort_limit_sim   = 4.1   (N*m)   — stall torque @ 12.0V, 2.3A
  velocity_limit_sim = 4.82  (rad/s) — no-load speed @ 12.0V, 46 rpm -> rad/s

NOT sourced from either BAM or the datasheet:
  stiffness — a position-control gain (Kp), not a measurable actuator
              property; still the old STS3215 placeholder (13.37) pending a
              deliberate choice.
  q_offset  — BAM's fitted joint zero-offset for the one physical unit on the
              test rig, not a per-robot design value; intentionally not
              applied anywhere.

USD path: generated by scripts/convert_urdf.sh from robot/robot.urdf (see
docs/onshape_import.md) via IsaacLab's UrdfConverter. Does NOT exist until
that script has been run on a machine with Isaac Sim.
"""

import os

import isaaclab.sim as sim_utils
from isaaclab.actuators import ImplicitActuatorCfg
from isaaclab.assets.articulation import ArticulationCfg

from .joint_order import (
    ACTUATOR_JOINT_NAMES,
    HOME_BASE_HEIGHT,
    HOME_JOINT_POS,
)

# Resolved relative to this repo's root, so the config works regardless of
# where the repo is checked out on the training machine.
_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OPEN_DUCK_MINI_USD_PATH = os.path.join(_REPO_ROOT, "robot", "usd", "open_duck_mini_v2.usd")

# Leg joints (10): position-servo XM430, this exact set drives locomotion.
_LEG_JOINT_NAMES = [n for n in ACTUATOR_JOINT_NAMES if "hip" in n or "knee" in n or "ankle" in n]
# Head joints (4): same physical servo, but not part of the imitation reward
# and given a commanded (not learned) target — see reward docs.
_HEAD_JOINT_NAMES = [n for n in ACTUATOR_JOINT_NAMES if n not in _LEG_JOINT_NAMES]

assert set(_LEG_JOINT_NAMES) | set(_HEAD_JOINT_NAMES) == set(ACTUATOR_JOINT_NAMES)
assert len(_LEG_JOINT_NAMES) == 10 and len(_HEAD_JOINT_NAMES) == 4

##
# Actuator config — single XM430 servo class covers all 14 actuated joints
# (kept as one group here since gains don't differ between legs/head, split
# into two ActuatorBaseCfg entries only because Isaac Lab groups actuators by
# joint_names_expr).
##

XM430_LEG_CFG = ImplicitActuatorCfg(
    joint_names_expr=_LEG_JOINT_NAMES,
    stiffness=13.37,
    damping=0.847,
    armature=0.01432,
    friction=0.0761,
    effort_limit_sim=4.1,
    velocity_limit_sim=4.82,
)

XM430_HEAD_CFG = ImplicitActuatorCfg(
    joint_names_expr=_HEAD_JOINT_NAMES,
    stiffness=13.37,
    damping=0.847,
    armature=0.01432,
    friction=0.0761,
    effort_limit_sim=4.1,
    velocity_limit_sim=4.82,
)

##
# Robot config
##

OPEN_DUCK_MINI_V2_CFG = ArticulationCfg(
    spawn=sim_utils.UsdFileCfg(
        usd_path=OPEN_DUCK_MINI_USD_PATH,
        activate_contact_sensors=True,
        rigid_props=sim_utils.RigidBodyPropertiesCfg(
            disable_gravity=False,
            retain_accelerations=False,
            linear_damping=0.0,
            angular_damping=0.0,
            max_linear_velocity=1000.0,
            max_angular_velocity=1000.0,
            max_depenetration_velocity=1.0,
        ),
        articulation_props=sim_utils.ArticulationRootPropertiesCfg(
            enabled_self_collisions=False,
            solver_position_iteration_count=4,
            solver_velocity_iteration_count=0,
        ),
    ),
    init_state=ArticulationCfg.InitialStateCfg(
        pos=(0.0, 0.0, HOME_BASE_HEIGHT),
        joint_pos=dict(HOME_JOINT_POS),
        joint_vel={".*": 0.0},
    ),
    soft_joint_pos_limit_factor=0.95,
    actuators={
        "legs": XM430_LEG_CFG,
        "head": XM430_HEAD_CFG,
    },
)
